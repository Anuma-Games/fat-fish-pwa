@Component({
  selector: 'app-pixel-icon',
  template: `<svg
    [attr.width]="size()"
    [attr.height]="size()"
    viewBox="0 0 12 12"
    shape-rendering="crispEdges"
    aria-hidden="true"
  >
    @for (p of pixeles(); track $index) {
      <rect [attr.x]="p[0]" [attr.y]="p[1]" width="1" height="1" fill="currentColor" />
    }
  </svg>`,
  styles: ':host { display: inline-flex; vertical-align: middle; }',
})
export class PixelIcon {
  readonly name = input.required<string>();
  readonly size = input(14);

  protected readonly pixeles = computed(() =>
    (ICONOS[this.name()] ?? []).flatMap((fila, y) =>
      [...fila].flatMap((c, x) => (c === '#' ? [[x, y]] : [])),
    ),
  );
}
